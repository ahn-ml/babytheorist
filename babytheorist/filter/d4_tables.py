"""D4 lookup tables for rule-based filtering.

Pre-computed so that every rule check at sampling time is a
dictionary / frozenset lookup — no BFS, no on-the-fly group theory.

Conventions
-----------
The :class:`babytheorist.symbolic.D4` type encodes ``(rot, flipped)`` with
``r = rot90`` (CCW) and ``s = flip_h``. Elements factor as
``r^rot · s^flipped``; composition follows ``srs = r^{-1}``.

Word length uses the three D4 primitives in the curriculum vocab::

    D4_PRIMITIVE_VOCAB = {"rot90", "flip_h", "flip_v"}

with generators

    r   = rot90  = D4(1, False)
    s   = flip_h = D4(0, True)
    r²s = flip_v = D4(2, True)

Exported tables
---------------
- :data:`D4_ELEMENTS`             — canonical ordering of all 8 elements.
- :data:`D4_IDENTITY`             — re-export for convenience.
- :data:`D4_SUBGROUPS`            — all 10 subgroups (as frozensets).
- :data:`D4_COMPOSE`              — (8 × 8) composition table ``g · h``.
- :data:`D4_INVERSE`              — inverse of each element.
- :data:`D4_WORD_LENGTH`          — word length in D4_PRIMITIVE_VOCAB.
- :data:`D4_PRIMITIVE_TO_ELEMENT` — primitive name → D4 element.

Lookup helpers
--------------
- :func:`compose`                  — ``g · h``.
- :func:`inverse`                  — inverse of ``g``.
- :func:`word_length`              — length of shortest word for ``g``.
- :func:`min_coset_word_length`    — ``min_{h ∈ g·H} word_length(h)``.
- :func:`allowed_stabilizers`      — all H's for which the coset's min
  word length equals ``d`` (i.e. stabilizers compatible with net
  effect ``g`` at per-shape depth ``d``).
"""

from __future__ import annotations

from collections import deque
from typing import Iterable

from babytheorist.symbolic import D4, D4_IDENTITY


__all__ = [
    "D4_PRIMITIVE_VOCAB",
    "D4_PRIMITIVE_TO_ELEMENT",
    "D4_ELEMENTS",
    "D4_IDENTITY",
    "D4_SUBGROUPS",
    "D4_COMPOSE",
    "D4_INVERSE",
    "D4_WORD_LENGTH",
    "compose",
    "inverse",
    "word_length",
    "min_coset_word_length",
    "stabilizers_allowed_at_depth",
    "stabilizers_forbidden_at_depth",
]


# === Primitive vocab ======================================================

D4_PRIMITIVE_VOCAB: frozenset[str] = frozenset({"rot90", "flip_h", "flip_v"})

# Each primitive's generator element (applied by left-multiplication:
# ``new_net = g_primitive · old_net``).
D4_PRIMITIVE_TO_ELEMENT: dict[str, D4] = {
    "rot90":  D4(1, False),   # r
    "flip_h": D4(0, True),    # s
    "flip_v": D4(2, True),    # r²s
}


# === Canonical ordering ===================================================

#: Canonical order: by rot (0-3), then by flipped (F, T).
D4_ELEMENTS: tuple[D4, ...] = tuple(
    D4(rot, flipped) for rot in range(4) for flipped in (False, True)
)

assert len(D4_ELEMENTS) == 8


# === Composition / inverse ================================================


def compose(g: D4, h: D4) -> D4:
    """Return ``g · h``.

    From the relation ``srs = r^{-1}``:

      - ``g.flipped = False`` (``g = r^a``): ``g · h = r^{a + h.rot} s^{h.f}``.
      - ``g.flipped = True``  (``g = r^a s``): ``g · h = r^{a - h.rot} s^{1 ⊕ h.f}``.
    """
    if g.flipped:
        new_rot = (g.rot - h.rot) % 4
    else:
        new_rot = (g.rot + h.rot) % 4
    return D4(new_rot, g.flipped != h.flipped)


def inverse(g: D4) -> D4:
    """Group inverse of ``g``.

    ``r^a`` inverts to ``r^{-a}``; any ``r^a · s`` has order 2 so is
    self-inverse.
    """
    if g.flipped:
        return g
    return D4((-g.rot) % 4, False)


#: 8×8 composition table indexed by :data:`D4_ELEMENTS`.
D4_COMPOSE: dict[tuple[D4, D4], D4] = {
    (g, h): compose(g, h) for g in D4_ELEMENTS for h in D4_ELEMENTS
}

D4_INVERSE: dict[D4, D4] = {g: inverse(g) for g in D4_ELEMENTS}


# === Subgroups ============================================================


def _closure(gens: Iterable[D4]) -> frozenset[D4]:
    """Return the subgroup generated by ``gens`` in D4."""
    seen: set[D4] = {D4_IDENTITY}
    frontier = list(gens)
    while frontier:
        g = frontier.pop()
        if g in seen:
            continue
        seen.add(g)
        for h in list(seen):
            for x in (compose(g, h), compose(h, g)):
                if x not in seen:
                    frontier.append(x)
    return frozenset(seen)


def _all_subgroups() -> tuple[frozenset[D4], ...]:
    """Enumerate all subgroups of D4. There are exactly 10."""
    subgroups: set[frozenset[D4]] = set()
    # Closure over every subset of size ≤ 2 already covers D4 (small group).
    subgroups.add(frozenset({D4_IDENTITY}))
    for g in D4_ELEMENTS:
        subgroups.add(_closure([g]))
    for i, g in enumerate(D4_ELEMENTS):
        for h in D4_ELEMENTS[i + 1:]:
            subgroups.add(_closure([g, h]))
    return tuple(sorted(subgroups, key=lambda S: (len(S), sorted((x.rot, x.flipped) for x in S))))


#: All 10 subgroups of D4, sorted by (size, lex of elements).
D4_SUBGROUPS: tuple[frozenset[D4], ...] = _all_subgroups()

assert len(D4_SUBGROUPS) == 10, f"expected 10 subgroups, got {len(D4_SUBGROUPS)}"


# === Word length ==========================================================


def _compute_word_lengths(vocab: frozenset[str]) -> dict[D4, int]:
    """BFS over Cayley graph with generators from ``vocab``.

    Word length is the minimum number of primitives that compose to
    the element (left-applied). ``word_length(e) = 0``.
    """
    generators = [D4_PRIMITIVE_TO_ELEMENT[name] for name in vocab]
    if not generators:
        raise ValueError("empty D4 vocab")

    lengths: dict[D4, int] = {D4_IDENTITY: 0}
    q: deque[D4] = deque([D4_IDENTITY])
    while q:
        g = q.popleft()
        for p in generators:
            h = compose(p, g)
            if h not in lengths:
                lengths[h] = lengths[g] + 1
                q.append(h)
    missing = [e for e in D4_ELEMENTS if e not in lengths]
    if missing:
        raise ValueError(f"vocab {vocab} does not generate D4 (missing: {missing})")
    return lengths


#: Word length of each D4 element under :data:`D4_PRIMITIVE_VOCAB`.
D4_WORD_LENGTH: dict[D4, int] = _compute_word_lengths(D4_PRIMITIVE_VOCAB)


def word_length(g: D4, vocab: frozenset[str] = D4_PRIMITIVE_VOCAB) -> int:
    """Shortest-word length for ``g`` using primitives from ``vocab``."""
    if vocab == D4_PRIMITIVE_VOCAB:
        return D4_WORD_LENGTH[g]
    return _compute_word_lengths(vocab)[g]


# === Coset min word length + stabilizer-depth table =======================


def min_coset_word_length(
    g: D4, H: frozenset[D4], vocab: frozenset[str] = D4_PRIMITIVE_VOCAB,
) -> int:
    """``min_{h ∈ g·H} word_length(h)`` — the shortest word that
    renders equivalent to ``g`` on any shape stabilized by ``H``.
    """
    wl = D4_WORD_LENGTH if vocab == D4_PRIMITIVE_VOCAB else _compute_word_lengths(vocab)
    return min(wl[compose(g, h)] for h in H)


def stabilizers_allowed_at_depth(
    g: D4, depth: int, vocab: frozenset[str] = D4_PRIMITIVE_VOCAB,
) -> frozenset[frozenset[D4]]:
    """Stabilizers ``H`` such that on a shape with ``Stab = H``, the
    shortest equivalent program has length ``≥ depth``.

    This is the rule-I1 lookup. Name is distinct from
    :attr:`ShapeConstraint.allowed_stabilizers` (which stores the
    *accumulated* candidate stabilizer set for a shape) to avoid
    conceptual clash.

    Parameters
    ----------
    g : D4
        Net D4 effect on the shape.
    depth : int
        The number of D4 primitives applied to the shape. The coset
        ``g · H`` must not contain any element with word length < depth.
    vocab : frozenset[str]
        D4 primitive vocabulary (default {rot90, flip_h, flip_v}).
    """
    if depth < 0:
        raise ValueError(f"depth must be non-negative, got {depth}")
    return frozenset(
        H for H in D4_SUBGROUPS
        if min_coset_word_length(g, H, vocab) >= depth
    )


def stabilizers_forbidden_at_depth(
    g: D4, depth: int, vocab: frozenset[str] = D4_PRIMITIVE_VOCAB,
) -> frozenset[frozenset[D4]]:
    """Complement of :func:`stabilizers_allowed_at_depth` —
    stabilizers that would permit a shorter-than-``depth`` rendering
    of program net effect ``g``.
    """
    return frozenset(D4_SUBGROUPS) - stabilizers_allowed_at_depth(g, depth, vocab)
