"""Phase 2 symbolic scene predicates — C(P).

For a program ``P`` and a concrete placed scene ``S``, ``is_scene_admissible``
returns ``True`` iff no strictly shorter program ``Q`` can render to the same
output grid as ``P(S)``. Used by ``generate._generate_pair`` to reject scenes
that admit curriculum-contaminating shortcuts, without the cost of brute-force
enumerating all ``Q`` candidates.

This is the rule-based complement to the brute-force
``_scene_has_shorter_shortcut`` in ``generate.py``. The brute-force path is
retained as an analysis tool (default off) — it grounds the oracle test that
validates C(P)'s soundness.

V1 scope — D4 symmetry only
---------------------------

Handles orient-only vocabs ``{rot90, flip_h, flip_v}`` with ``ALL`` or
``by_index`` selectors. Detects shape-stabilizer shortcuts where a program
composes to orient ``g`` that, on this scene, renders identically to some
shorter-word orient ``g'`` — i.e., ``g^{-1} g' ∈ Stab(scene)``.

Out-of-scope programs defer (return ``True``); Phase 2's existing identity
backstop + ``grid_sequence_all_distinct`` still catch the most egregious
cases, and the deferred coverage is the target of V2/V3 work.
"""

