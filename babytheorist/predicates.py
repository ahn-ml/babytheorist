# The 8 elements of D4. Useful for stabilizer enumeration.
D4_ALL: frozenset[D4] = frozenset(
    D4(rot, flipped) for rot in range(4) for flipped in (False, True)
)


_V1_VOCAB = frozenset({"rot90", "flip_h", "flip_v"})

# All selector types V1 handles. D4 primitives are position/color/
# grid-shape preserving, so every dynamic selector's resolution on the
# initial scene carries through the program unchanged — we can resolve
# each selector to a concrete shape-subset once and do the analysis in
# "subset vocabulary" space.
_V1_SUPPORTED_SELECTORS = frozenset({
    "ALL", "by_index", "by_color", "is_hollow",
    "topmost", "bottommost", "leftmost", "rightmost",
})

# Map D4 primitive name to its generator D4 element (applied on the
# left: new_orient = prim · current_orient).
_PRIMITIVE_TO_D4 = {
    "rot90": D4(1, False),
    "flip_h": D4(0, True),
    "flip_v": D4(2, True),
}


# === D4 composition ========================================================


def compose_d4(g: D4, h: D4) -> D4:
    """Return ``g · h`` in D4.

    D4 is generated by ``r = rot90`` (CCW) and ``s = flip_h`` (BabyTheorist
    convention ``flipud``) with relations ``r^4 = s^2 = e`` and
    ``srs = r^{-1}``. Each element is uniquely ``r^a · s^f`` with
    ``0 ≤ a < 4`` and ``f ∈ {0, 1}``.

    Derivation:
      ``(r^{g.rot} s^{g.f}) · (r^{h.rot} s^{h.f})``
      → if ``g.f = 0``: ``r^{g.rot + h.rot} s^{h.f}``
      → if ``g.f = 1``: ``r^{g.rot} · s r^{h.rot} · s^{h.f}
                      = r^{g.rot - h.rot} s^{1 + h.f}``.

    The ``symbolic.D4.apply_rot/apply_flip_h/apply_flip_v`` methods encode
    *left* multiplication by the named primitive (``r · g``, ``s · g``,
    ``r²s · g``); ``compose_d4`` is the general form they specialise.
    """
    if g.flipped:
        new_rot = (g.rot - h.rot) % 4
    else:
        new_rot = (g.rot + h.rot) % 4
    new_flipped = g.flipped != h.flipped
    return D4(new_rot, new_flipped)


def inverse_d4(g: D4) -> D4:
    """Group inverse of ``g`` in D4.

    - ``r^a`` has inverse ``r^{-a}``.
    - ``r^a · s`` is self-inverse: ``(r^a s)(r^a s) = r^a (sr^a) s
                                  = r^a r^{-a} s s = e``.
    """
    if g.flipped:
        return g
    return D4((-g.rot) % 4, False)


# === D4 action on pixel grids =============================================


def apply_d4_to_grid(grid: np.ndarray, g: D4) -> np.ndarray:
    """Apply ``g`` to a 2D pixel grid.

    Operationally ``g · grid = r^{g.rot} (s^{g.f}(grid))`` — first flip (if
    ``g.flipped``), then rotate ``g.rot`` quarter turns CCW.

    Matches the BabyTheorist primitive convention:
      - ``rot90(shape) = np.rot90(grid, 1)`` (CCW)
      - ``flip_h(shape) = np.flipud(grid)`` (``s`` in our D4 representation)
      - ``flip_v(shape) = np.fliplr(grid) = r² · s``

    Non-square inputs may change ``shape[0]/shape[1]`` under odd rotations;
    callers comparing to the original grid must check shape equality first.
    """
    out = grid
    if g.flipped:
        out = np.flipud(out)
    if g.rot != 0:
        out = np.rot90(out, k=g.rot)
    return out


# === Stabilizer =============================================================


def stabilizer_of_pixel_grid(grid: np.ndarray) -> frozenset[D4]:
    """The subgroup ``Stab(grid) = {g ∈ D4 : g · grid = grid}``.

    Iterates all 8 elements and keeps those that (a) preserve grid shape
    after transformation and (b) match pixel-for-pixel. Colors are part of
    the check — a silhouette-symmetric shape with asymmetric color pattern
    has a smaller stabilizer than the silhouette alone.

    An all-zero grid has full D4 stabilizer (trivially preserved by every
    transform of matching shape). The shape-mismatch guard handles non-
    square grids cleanly — no odd rotation can fix them, so ``rot90``/
    ``rot270`` naturally drop out.
    """
    result: set[D4] = set()
    for g in D4_ALL:
        if g == D4_IDENTITY:
            result.add(g)
            continue
        transformed = apply_d4_to_grid(grid, g)
        if transformed.shape == grid.shape and np.array_equal(transformed, grid):
            result.add(g)
    return frozenset(result)


def stabilizer_of_silhouette(grid: np.ndarray) -> frozenset[D4]:
    """Stab of the shape's binary silhouette (``grid != 0``) — ignores
    color distinctions.

    Always a superset of ``stabilizer_of_pixel_grid(grid)``. Used by
    Phase C to detect "effective stabilizer increases when colors
    collapse" (e.g. swap_colors makes a 2-color shape monochrome; its
    rendering now has the silhouette's full Stab, not the smaller
    color-aware one).
    """
    silhouette = (grid != 0).astype(np.int64)
    return stabilizer_of_pixel_grid(silhouette)


def stabilizer_of_scene(positioned: list[Shape]) -> frozenset[D4]:
    """Intersection of per-shape stabilizers — the D4 subgroup under
    which *every* shape in the scene is preserved.

    Under ``ALL`` selector + position-preserving vocab, ``g`` and ``g'``
    render identically iff ``g^{-1} g' ∈ Stab_common``. Empty scene → full
    D4 (vacuous intersection).
    """
    if not positioned:
        return D4_ALL
    result = D4_ALL
    for shape in positioned:
        result = result & stabilizer_of_pixel_grid(shape.grid)
    return result


# === Coset min-depth =======================================================


def min_depth_in_coset(
    g: D4, H: frozenset[D4], vocab: frozenset[str],
) -> int:
    """Minimum word-length over the left coset ``g · H``, in primitives
    from ``vocab``.

    The coset is the set of D4 elements rendering-equivalent to ``g``
    on any shape stabilized by ``H``. If the coset contains an element
    reachable in fewer than ``min_depth_orient(g, vocab)`` primitives,
    a strictly shorter program exists that renders identically — a
    shortcut.

    Unreachable coset elements are skipped. ``g`` itself is always
    reachable (P built it), so the min over the reachable subset is
    well-defined.
    """
    table = d4_min_depths(vocab)
    best: int | None = None
    for h in H:
        member = compose_d4(g, h)
        if member not in table:
            continue
        d = table[member]
        if best is None or d < best:
            best = d
    if best is None:
        # Should not happen — g itself is in the coset (via h=e) and was
        # reachable by P.
        raise RuntimeError(
            f"min_depth_in_coset: coset of {g!r} under {sorted(H)!r} has no "
            f"reachable element under vocab {sorted(vocab)!r}"
        )
    return best


# === Program → D4 ==========================================================


def compose_program_to_d4(program: Program) -> D4:
    """Net D4 orientation after applying ``program`` to a shape with
    initial orient ``e``. Only valid when every step's primitive is in
    the D4 vocab ``{rot90, flip_h, flip_v}``; raises ``ValueError``
    otherwise.
    """
    g = D4_IDENTITY
    for step in program:
        name = step.primitive
        if name == "rot90":
            g = g.apply_rot()
        elif name == "flip_h":
            g = g.apply_flip_h()
        elif name == "flip_v":
            g = g.apply_flip_v()
        else:
            raise ValueError(
                f"compose_program_to_d4: primitive {name!r} outside D4 vocab"
            )
    return g


# === V3 color axis — scene-parameterized Tier 4 ===========================
#
# Phase 1 Tier 4 (``canonical.color_joint_bfs_table``) runs BFS in the
# joint-ColorVal state space, using symbolic initial state
# ``(ColorVal(str(i), 0) for i)`` — every shape has a *distinct* symbolic
# color. It rejects programs whose net color effect needs strictly fewer
# primitives than ``len(P)``. What it *misses* is shortcuts driven by
# **scene-level color coincidences**: two shapes whose symbolic colors
# are distinct but whose scene-concrete primary_color happens to be
# equal, so a swap between them is permutation-wise redundant.
#
# V3 re-runs the same BFS, but starts from ``tuple(shape.primary_color
# for shape in scene)`` — concrete ints. Transitions:
#   - ``next_color``: c_k → (c_k % 9) + 1 (matches ``primitives.next_color``).
#   - ``swap_colors(i, j)`` (by_index): swap c_i and c_j if distinct;
#     otherwise precondition fails and the transition is skipped.
# State space is ≤ 9^n_shapes — 729 at n=3 — so BFS is instant.
#
# **Scope restriction** — single-color shapes only. ``next_color`` shifts
# *every* non-zero pixel; ``swap_colors`` only moves pixels currently at
# the *primary* color. If a shape has secondary colors (bordered /
# patterned / striped), primary-only tracking becomes unsound because
# secondary-color placement distinguishes otherwise-primary-equal states.
# So V3 activates iff every shape in the scene has exactly one non-zero
# color (``len(shape.colors) == 1``). Solid and hollow shapes qualify;
# bordered / patterned defer.


_COLOR_PRIMITIVES = frozenset({"next_color", "swap_colors"})

# Selectors whose scene-resolution is invariant under color primitives.
# Excludes ``by_color`` because ``next_color`` and ``swap_colors`` change
# primary_color, so ``by_color(c)`` would resolve differently at different
# steps.
_V3_COLOR_STABLE_SELECTORS = frozenset({
    "ALL", "by_index", "is_hollow",
    "topmost", "bottommost", "leftmost", "rightmost",
})

# Subset of those that are single-select (usable as relational src/tgt).
_V3_COLOR_SINGLE_SELECTORS = frozenset({
    "by_index", "topmost", "bottommost", "leftmost", "rightmost",
})


def _next_color_concrete(c: int) -> int:
    """Concrete ``next_color`` transition on a single color value.
    Matches ``babytheorist.primitives.next_color``: ``(c % 9) + 1``."""
    return (c % 9) + 1


def enumerate_single_index_vocabulary(
    level_selectors: frozenset[str],
    positioned: list[Shape],
    allowed_single_selectors: frozenset[str],
) -> frozenset[int]:
    """Shape indices reachable by some *single-selector* in
    ``level_selectors``.

    Used for relational-primitive src/tgt enumeration (swap_colors,
    align_row, align_col all require single-selectors).
    """
    indices: set[int] = set()
    singles = level_selectors & allowed_single_selectors
    for sel_type in singles:
        if sel_type == "by_index":
            indices.update(range(len(positioned)))
        else:
            resolved = select(Selector(sel_type), positioned)
            indices.update(resolved)
    return frozenset(indices)


def scene_color_bfs(
    target: tuple[int, ...],
    initial: tuple[int, ...],
    vocab: frozenset[str],
    subset_vocab: frozenset[frozenset[int]],
    pair_vocab: frozenset[tuple[int, int]],
    max_depth: int,
) -> int:
    """BFS over joint primary-color tuples from ``initial`` looking for
    the first depth at which ``target`` is reachable. Returns that
    depth, or ``max_depth + 1`` if not found.

    Transitions:
      - ``next_color`` with subset S: for each ``k ∈ S``,
        ``c_k → (c_k % 9) + 1``.
      - ``swap_colors`` with pair (i, j): swap ``c_i`` and ``c_j`` if
        distinct (else precondition fail, skip).

    ``subset_vocab`` / ``pair_vocab`` are scene-resolved (via
    ``enumerate_subset_vocabulary`` / ``enumerate_single_index_vocabulary``).
    """
    if initial == target:
        return 0
    distances: dict[tuple[int, ...], int] = {initial: 0}
    frontier: list[tuple[int, ...]] = [initial]
    while frontier:
        nxt: list[tuple[int, ...]] = []
        for state in frontier:
            d = distances[state]
            if d >= max_depth:
                continue
            if "next_color" in vocab:
                for subset in subset_vocab:
                    new_state = list(state)
                    for k in subset:
                        new_state[k] = _next_color_concrete(new_state[k])
                    ns = tuple(new_state)
                    if ns in distances:
                        continue
                    distances[ns] = d + 1
                    if ns == target:
                        return d + 1
                    nxt.append(ns)
            if "swap_colors" in vocab:
                for (i, j) in pair_vocab:
                    if state[i] == state[j]:
                        continue  # engine precondition
                    new_state = list(state)
                    new_state[i], new_state[j] = new_state[j], new_state[i]
                    ns = tuple(new_state)
                    if ns in distances:
                        continue
                    distances[ns] = d + 1
                    if ns == target:
                        return d + 1
                    nxt.append(ns)
        frontier = nxt
    return max_depth + 1


def trace_program_colors(
    program: Program,
    initial: tuple[int, ...],
    positioned: list[Shape] | None = None,
) -> tuple[int, ...] | None:
    """Thread a color-only program through a color-state tuple.

    When ``positioned`` is provided, selectors are resolved against the
    concrete scene (handles dynamic selectors: topmost / by_color /
    is_hollow / etc.). When ``positioned`` is ``None``, only ``ALL``
    and ``by_index`` selectors are supported — useful for direct unit
    testing of transition semantics without building a full scene.

    Returns the final color tuple, or ``None`` on precondition fail
    (e.g. ``swap_colors`` with equal primaries, empty selector match).
    """
    state = list(initial)
    n = len(state)
    for step in program:
        name = step.primitive
        sel = step.selector
        tgt = step.target
        if name == "next_color":
            if positioned is not None:
                indices = select(sel, positioned)
                if not indices:
                    return None
                for k in indices:
                    state[k] = _next_color_concrete(state[k])
            else:
                # Legacy 2-arg path: ALL or by_index only.
                if sel.type == "ALL":
                    state = [_next_color_concrete(c) for c in state]
                elif sel.type == "by_index":
                    k = sel.param - 1
                    if not (0 <= k < n):
                        return None
                    state[k] = _next_color_concrete(state[k])
                else:
                    return None
        elif name == "swap_colors":
            if tgt is None:
                return None
            if positioned is not None:
                src = select(sel, positioned)
                t = select(tgt, positioned)
                if len(src) != 1 or len(t) != 1:
                    return None
                i, j = src[0], t[0]
            else:
                if sel.type != "by_index" or tgt.type != "by_index":
                    return None
                i, j = sel.param - 1, tgt.param - 1
                if not (0 <= i < n) or not (0 <= j < n):
                    return None
            if i == j or state[i] == state[j]:
                return None
            state[i], state[j] = state[j], state[i]
        else:
            return None
    return tuple(state)


def _is_v3_color_scope(
    program: Program,
    positioned: list[Shape],
    vocab: frozenset[str],
    level_selectors: frozenset[str],
) -> bool:
    """True iff (program, scene, vocab, level_selectors) is in the V3
    color-axis scope."""
    # Vocab must be pure color.
    if not vocab or not vocab <= _COLOR_PRIMITIVES:
        return False
    # Program steps: color primitives only, color-stable selectors.
    for step in program:
        if step.primitive not in _COLOR_PRIMITIVES:
            return False
        if step.selector.type not in _V3_COLOR_STABLE_SELECTORS:
            return False
        if step.target is not None and step.target.type not in _V3_COLOR_SINGLE_SELECTORS:
            return False
    # Level selector constraint.
    if not level_selectors <= _V3_COLOR_STABLE_SELECTORS:
        return False
    if ("swap_colors" in vocab
            and not (level_selectors & _V3_COLOR_SINGLE_SELECTORS)):
        return False
    # Scene constraint: every shape has a single non-zero color (solid
    # or hollow). Bordered / patterned shapes defer (secondary colors
    # make primary-tracking unsound — see module docstring).
    for shape in positioned:
        if shape.is_null:
            return False
        if len(shape.colors) != 1:
            return False
    return True


def _is_scene_admissible_v3_color(
    program: Program,
    positioned: list[Shape],
    vocab: frozenset[str],
    level_selectors: frozenset[str],
    palette: tuple[int, ...] = (1, 2, 3, 4, 5, 6, 7, 8, 9),
) -> bool:
    """V3 color-axis scene predicate — scene-parameterized Tier 4 BFS.
    Assumes caller has already verified V3 scope."""
    initial = tuple(shape.primary_color for shape in positioned)
    target = trace_program_colors(program, initial, positioned)
    if target is None:
        # Program fails on this scene's initial colors. Engine will
        # reject the pair — defer (accept).
        return True
    subset_vocab = enumerate_subset_vocabulary(
        level_selectors, positioned, palette,
    )
    single_indices = enumerate_single_index_vocabulary(
        level_selectors, positioned, _V3_COLOR_SINGLE_SELECTORS,
    )
    pair_vocab = frozenset(
        (i, j) for i in single_indices for j in single_indices if i != j
    )
    min_depth = scene_color_bfs(
        target, initial, vocab, subset_vocab, pair_vocab,
        max_depth=max(0, len(program) - 1),
    )
    return min_depth >= len(program)


# === V3 position axis — scene-parameterized Tier 5 ========================
#
# Phase 1 Tier 5 (``canonical.row_col_source_joint_bfs_table``) runs BFS
# in the "source label" space: each shape carries the index of the shape
# whose initial row/col it currently adopts. Initial state:
# ``(0, 1, 2, ...)``, transitions: ``align_row(i, j)`` copies
# ``row_source[j]`` into ``row_source[i]``. It rejects align programs
# whose effect has a shorter source-label equivalent.
#
# What it misses: scene-level coincidences — if two shapes happen to
# share an initial row, a program that aligns A to B's row may be
# equivalent to one that aligns A to C's row.
#
# V3 position re-runs the BFS with scene-concrete initial rows/cols.
# Transitions skip equal-value precondition fails (matching engine).
# Collision checks are omitted (a collision-failed Q isn't really a
# shortcut, so we may over-reject — that's still sound).
#
# **Scope**:
#   - vocab ⊆ {align_row, align_col}.
#   - level_selectors ⊆ {by_index}. (align is relational — single-
#     selectors required; by_index is the only single selector V3
#     handles.)
#   - n_shapes ≥ 2.


_ALIGN_PRIMITIVES = frozenset({"align_row", "align_col"})

# Selectors whose scene-resolution is invariant under align primitives.
# ``align_row``/``align_col`` change shape positions, so position-based
# dynamic selectors (``topmost``/``bottommost``/``leftmost``/
# ``rightmost``) are *unstable* — their resolution depends on whatever
# positions the shapes hold at each step. Other selectors look at
# fixed attributes (primary_color, grid_shape, raster index) that
# align doesn't touch, so they are stable.
_V3_POSITION_STABLE_SELECTORS = frozenset({
    "ALL", "by_index", "by_color", "is_hollow",
})


def scene_position_bfs(
    initial_rows: tuple[int, ...],
    initial_cols: tuple[int, ...],
    vocab: frozenset[str],
    max_depth: int,
) -> dict[tuple[tuple[int, ...], tuple[int, ...]], int]:
    """BFS over joint ``(rows, cols)`` tuples under align primitives.

    Each transition is an ``align_row(i, j)`` or ``align_col(i, j)``
    with ``i ≠ j`` and the corresponding current values distinct
    (engine precondition).  Returns distance dict keyed on
    ``(rows_tuple, cols_tuple)``.
    """
    n = len(initial_rows)
    initial: tuple[tuple[int, ...], tuple[int, ...]] = (
        initial_rows, initial_cols,
    )
    distances: dict = {initial: 0}
    frontier = [initial]
    while frontier:
        nxt = []
        for state in frontier:
            d = distances[state]
            if d >= max_depth:
                continue
            rows, cols = state
            if "align_row" in vocab:
                for i in range(n):
                    for j in range(n):
                        if i == j or rows[i] == rows[j]:
                            continue
                        new_rows = list(rows)
                        new_rows[i] = rows[j]
                        ns = (tuple(new_rows), cols)
                        if ns not in distances:
                            distances[ns] = d + 1
                            nxt.append(ns)
            if "align_col" in vocab:
                for i in range(n):
                    for j in range(n):
                        if i == j or cols[i] == cols[j]:
                            continue
                        new_cols = list(cols)
                        new_cols[i] = cols[j]
                        ns = (rows, tuple(new_cols))
                        if ns not in distances:
                            distances[ns] = d + 1
                            nxt.append(ns)
        frontier = nxt
    return distances


def trace_program_positions(
    program: Program,
    initial_rows: tuple[int, ...],
    initial_cols: tuple[int, ...],
) -> tuple[tuple[int, ...], tuple[int, ...]] | None:
    """Thread an align-only program through concrete scene positions.
    Returns the final ``(rows, cols)``, or ``None`` on precondition
    fail (equal-value align, out-of-range index).
    """
    rows = list(initial_rows)
    cols = list(initial_cols)
    n = len(rows)
    for step in program:
        name = step.primitive
        sel = step.selector
        tgt = step.target
        if name not in _ALIGN_PRIMITIVES:
            return None
        if (tgt is None or sel.type != "by_index"
                or tgt.type != "by_index"):
            return None
        i, j = sel.param - 1, tgt.param - 1
        if not (0 <= i < n) or not (0 <= j < n) or i == j:
            return None
        if name == "align_row":
            if rows[i] == rows[j]:
                return None
            rows[i] = rows[j]
        else:  # align_col
            if cols[i] == cols[j]:
                return None
            cols[i] = cols[j]
    return tuple(rows), tuple(cols)


def _is_v3_position_scope(
    program: Program,
    positioned: list[Shape],
    vocab: frozenset[str],
    level_selectors: frozenset[str],
) -> bool:
    """True iff (program, scene, vocab, level_selectors) is in V3
    position-axis scope.

    - ``vocab`` ⊆ {align_row, align_col}.
    - Level must include ``by_index`` (the only stable single-selector
      for align src/tgt).
    - Level must not include position-based dynamic selectors
      (``topmost`` / ``bottommost`` / ``leftmost`` / ``rightmost``) —
      they are unstable under align.
    - Multi-selectors (ALL, by_color, is_hollow) in level are fine —
      align doesn't use them.
    - Program steps: align_* with by_index src/tgt (the only stable
      single selector).
    """
    if not vocab or not vocab <= _ALIGN_PRIMITIVES:
        return False
    if len(positioned) < 2:
        return False
    if "by_index" not in level_selectors:
        return False
    if not level_selectors <= _V3_POSITION_STABLE_SELECTORS:
        return False
    # Program: align_* only; by_index for both src and tgt (position-
    # based singles unstable).
    for step in program:
        if step.primitive not in _ALIGN_PRIMITIVES:
            return False
        if step.selector.type != "by_index":
            return False
        if step.target is None or step.target.type != "by_index":
            return False
    return True


def _is_scene_admissible_v3_position(
    program: Program,
    positioned: list[Shape],
    vocab: frozenset[str],
) -> bool:
    """V3 position-axis: scene-parameterized Tier 5 BFS. Assumes scope
    check passed."""
    initial_rows = tuple(s.position[0] for s in positioned)
    initial_cols = tuple(s.position[1] for s in positioned)
    final = trace_program_positions(program, initial_rows, initial_cols)
    if final is None:
        return True  # program fails on scene — engine rejects, defer.
    depth = len(program)
    distances = scene_position_bfs(initial_rows, initial_cols, vocab, depth)
    min_depth = distances.get(final)
    if min_depth is None:
        return True
    return depth == min_depth


# === V2 translate + add_border — scene-parameterized Tier 2/3 =============
#
# Phase 1 Tier 2/3 (``canonical.orient_position_bfs_table`` and
# ``orient_border_position_bfs_table``) do joint BFS over
# ``(orient, rh, rw, ch, cw[, border, rc, cc])`` — abstract coefficients
# on a single shape's initial ``(h, w)``. Symbolic: same abstract
# analysis applies to every scene.
#
# V2 re-runs per-shape BFS with **concrete** initial ``(r, c, h, w)``
# per shape. Catches shortcuts where scene-specific equalities
# (``h_k = w_k`` for a square shape, or just that different abstract
# coefficient combinations land at the same concrete row/col) break
# Phase 1's abstract distinctness.
#
# **Scope**:
#   - ``vocab`` ⊆ {D4 ∪ translate_* ∪ add_border}.
#   - ``level_selectors == {by_index}`` strictly. Any multi-selector
#     (ALL, by_color, is_hollow) in the level would let a Q apply a
#     single op to multiple shapes at once; per-shape decomposition
#     would then miss the parallelism shortcut. For raster-style
#     curricula (selectors=by_index only), this matches natively.
#   - Program: every step uses by_index.
#
# State per shape: ``(orient, border_count, row, col)``. Stabilizer
# is computed on the original shape grid (add_border preserves all
# D4 symmetries of the original, so it's state-independent).

_V2_TRANSLATE_PRIMITIVES = frozenset({
    "translate_up", "translate_down", "translate_left", "translate_right",
})
_V2_VOCAB = _V1_VOCAB | _V2_TRANSLATE_PRIMITIVES | frozenset({"add_border"})


def _apply_v2_primitive(
    state: tuple[D4, int, int, int],
    primitive: str,
    h_init: int, w_init: int,
) -> tuple[D4, int, int, int] | None:
    """Apply one V2 primitive to per-shape ``(orient, border, row,
    col)``. Returns ``None`` on unknown primitive."""
    orient, border, row, col = state
    if primitive == "rot90":
        return (orient.apply_rot(), border, row, col)
    if primitive == "flip_h":
        return (orient.apply_flip_h(), border, row, col)
    if primitive == "flip_v":
        return (orient.apply_flip_v(), border, row, col)
    # Translate uses current (post-orient, post-border) height/width.
    parity = orient.rot % 2
    cur_h = (h_init if parity == 0 else w_init) + 2 * border
    cur_w = (w_init if parity == 0 else h_init) + 2 * border
    if primitive == "translate_up":
        return (orient, border, row - cur_h, col)
    if primitive == "translate_down":
        return (orient, border, row + cur_h, col)
    if primitive == "translate_left":
        return (orient, border, row, col - cur_w)
    if primitive == "translate_right":
        return (orient, border, row, col + cur_w)
    if primitive == "add_border":
        return (orient, border + 1, row - 1, col - 1)
    return None


def trace_sub_program_v2(
    sub_program: list[Step],
    h_init: int, w_init: int,
    r_init: int, c_init: int,
) -> tuple[D4, int, int, int] | None:
    """Trace a single-shape sub-program (all steps target this shape)
    through ``(orient, border, row, col)``. Returns final state or
    ``None`` on unsupported primitive."""
    state: tuple[D4, int, int, int] = (D4_IDENTITY, 0, r_init, c_init)
    for step in sub_program:
        new_state = _apply_v2_primitive(
            state, step.primitive, h_init, w_init,
        )
        if new_state is None:
            return None
        state = new_state
    return state


def per_shape_v2_bfs(
    target: tuple[D4, int, int, int],
    h_init: int, w_init: int,
    r_init: int, c_init: int,
    primitive_vocab: frozenset[str],
    stab: frozenset[D4],
    max_depth: int,
) -> int:
    """BFS over per-shape ``(orient, border, row, col)`` state from the
    initial scene position, under V2 primitive vocabulary.

    Returns the minimum depth at which a state render-equivalent to
    ``target`` is reached (render-equiv per shape: orient matches
    ``target.orient`` modulo ``stab``, ``(border, row, col)`` match
    exactly — different border/position mean different world pixels).

    Returns ``max_depth + 1`` if not found within ``max_depth`` ops.
    """
    initial: tuple[D4, int, int, int] = (D4_IDENTITY, 0, r_init, c_init)

    def equiv(state: tuple[D4, int, int, int]) -> bool:
        g, b, r, c = state
        tg, tb, tr, tc = target
        if b != tb or r != tr or c != tc:
            return False
        return compose_d4(inverse_d4(tg), g) in stab

    if equiv(initial):
        return 0
    distances: dict[tuple[D4, int, int, int], int] = {initial: 0}
    frontier: list[tuple[D4, int, int, int]] = [initial]
    prims = tuple(primitive_vocab)
    while frontier:
        nxt: list[tuple[D4, int, int, int]] = []
        for state in frontier:
            d = distances[state]
            if d >= max_depth:
                continue
            for prim in prims:
                new_state = _apply_v2_primitive(state, prim, h_init, w_init)
                if new_state is None or new_state in distances:
                    continue
                distances[new_state] = d + 1
                if equiv(new_state):
                    return d + 1
                nxt.append(new_state)
        frontier = nxt
    return max_depth + 1


def _is_v2_scope(
    program: Program,
    positioned: list[Shape],
    vocab: frozenset[str],
    level_selectors: frozenset[str],
) -> bool:
    """True iff (program, scene, vocab, level_selectors) is in V2 scope:
    V2 primitive vocab with at least one translate or add_border (else
    V1 is the tighter branch), by_index-only level, by_index-only
    program."""
    if not vocab or not vocab <= _V2_VOCAB:
        return False
    if not (vocab & (_V2_TRANSLATE_PRIMITIVES | frozenset({"add_border"}))):
        return False  # V1 handles pure D4
    if level_selectors != frozenset({"by_index"}):
        return False
    for step in program:
        if step.primitive not in _V2_VOCAB:
            return False
        if step.selector.type != "by_index":
            return False
        if step.target is not None:
            return False
    return True


def _is_scene_admissible_v2(
    program: Program, positioned: list[Shape], vocab: frozenset[str],
) -> bool:
    """V2 by_index scope: split program into per-shape sub-programs,
    run per-shape scene-concrete BFS to confirm each sub-prog is
    minimal. Any per-shape shortcut → reject."""
    n = len(positioned)
    sub_programs: dict[int, list[Step]] = {k: [] for k in range(n)}
    for step in program:
        k = step.selector.param - 1
        if not (0 <= k < n):
            return True  # selector out of range — engine would fail
        sub_programs[k].append(step)
    for k, shape in enumerate(positioned):
        sub = sub_programs[k]
        if not sub:
            continue
        r_init, c_init = shape.position
        h_init, w_init = shape.grid.shape[0], shape.grid.shape[1]
        target = trace_sub_program_v2(sub, h_init, w_init, r_init, c_init)
        if target is None:
            return True  # defer on unsupported primitive
        stab = stabilizer_of_pixel_grid(shape.grid)
        min_depth = per_shape_v2_bfs(
            target, h_init, w_init, r_init, c_init,
            vocab, stab, max_depth=max(0, len(sub) - 1),
        )
        if min_depth < len(sub):
            return False
    return True


# === Phase C — Joint BFS across all axes ==================================
#
# V1/V2/V3 each handle a single axis (orient / translate+border /
# color / position). For programs with **mixed vocabulary** — say
# D4 + color + translate — none of those branches fire. Phase C
# provides a catch-all joint BFS over the full per-shape state
# ``(orient, border, row, col, color, grid_shape)``.
#
# **Scope**:
#   - ``vocab`` ⊆ {all 14 primitives}.
#   - ``level_selectors == {by_index}`` strictly (multi-selector Q
#     would break per-shape joint analysis symmetry; by_index only
#     for simplicity).
#   - Single-color shapes (as in V3 color).
#   - Mixed-axis vocab: at least two of {D4, translate_or_border,
#     color, align, grid_shape-changing} present, so none of the
#     faster V1/V2/V3 branches claim the scope.

_V_ALL_SUPPORTED_PRIMITIVES = (
    _V1_VOCAB                                       # D4
    | _V2_TRANSLATE_PRIMITIVES | frozenset({"add_border"})
    | _COLOR_PRIMITIVES
    | _ALIGN_PRIMITIVES
    | frozenset({"hollow", "fill_interior"})
)

_GRID_SHAPE_SOLID = "solid"
_GRID_SHAPE_HOLLOW = "hollow"

_RELATIONAL_PRIMS = frozenset({"swap_colors", "align_row", "align_col"})


def _resolve_selector_on_joint_state(sel: Selector, state: tuple) -> tuple:
    """Resolve a selector against the current joint state (tuple of
    per-shape ``(orient, border, row, col, primary, secondary, gshape)``).

    Returns a tuple of matching shape indices (possibly empty).
    """
    n = len(state)
    t = sel.type
    if t == "ALL":
        return tuple(range(n))
    if t == "by_index":
        k = sel.param
        return (k - 1,) if (k is not None and 1 <= k <= n) else ()
    if t == "by_color":
        return tuple(i for i in range(n) if state[i][4] == sel.param)
    if t == "is_hollow":
        return tuple(i for i in range(n)
                     if state[i][6] == _GRID_SHAPE_HOLLOW)
    if t in ("topmost", "bottommost", "leftmost", "rightmost"):
        if n == 0:
            return ()
        if t == "topmost":
            idx = min(range(n), key=lambda i: (state[i][2], state[i][3]))
        elif t == "bottommost":
            idx = max(range(n), key=lambda i: (state[i][2], state[i][3]))
        elif t == "leftmost":
            idx = min(range(n), key=lambda i: (state[i][3], state[i][2]))
        else:  # rightmost
            idx = max(range(n), key=lambda i: (state[i][3], state[i][2]))
        return (idx,)
    return ()


# Per-shape state for joint BFS:
#   (orient, border, row, col, primary_color, secondary_color,
#    grid_shape)
# ``secondary_color`` is the shape's second-most-frequent non-zero
# color or ``None`` for single-color shapes. Both colors shift under
# next_color; swap_colors only swaps primary (secondary stays with
# its shape). This representation subsumes the single-color case
# (``secondary_color=None``) and handles bordered / patterned shapes.


def _apply_joint_step(
    state: tuple[tuple, ...],
    step: Step,
    h_inits: tuple[int, ...],
    w_inits: tuple[int, ...],
    hollow_drops_sec: tuple[bool, ...] = (),
) -> tuple[tuple, ...] | None:
    """Apply one step to joint state.

    Selectors (static + dynamic) are resolved against the current state
    via ``_resolve_selector_on_joint_state`` — so the same function
    handles by_index and attribute-style selectors uniformly.

    Returns new joint state or ``None`` on precondition fail / selector
    miss / unsupported primitive.
    """
    prim = step.primitive
    sel = step.selector
    tgt = step.target
    n = len(state)

    if prim in _RELATIONAL_PRIMS:
        if tgt is None:
            return None
        src_indices = _resolve_selector_on_joint_state(sel, state)
        tgt_indices = _resolve_selector_on_joint_state(tgt, state)
        if len(src_indices) != 1 or len(tgt_indices) != 1:
            return None  # relational requires exactly one each
        i, j = src_indices[0], tgt_indices[0]
        if i == j:
            return None
        new_state = list(state)
        if prim == "swap_colors":
            pi = new_state[i][4]
            pj = new_state[j][4]
            if pi == pj:
                return None
            new_state[i] = (*new_state[i][:4], pj,
                            new_state[i][5], new_state[i][6])
            new_state[j] = (*new_state[j][:4], pi,
                            new_state[j][5], new_state[j][6])
        elif prim == "align_row":
            if new_state[i][2] == new_state[j][2]:
                return None
            new_state[i] = (*new_state[i][:2], new_state[j][2],
                            *new_state[i][3:])
        elif prim == "align_col":
            if new_state[i][3] == new_state[j][3]:
                return None
            new_state[i] = (*new_state[i][:3], new_state[j][3],
                            *new_state[i][4:])
        else:
            return None
        return tuple(new_state)

    # Non-relational: apply primitive to each resolved index.
    indices = _resolve_selector_on_joint_state(sel, state)
    if not indices:
        return None
    new_state = list(state)
    for i in indices:
        orient, border, row, col, prim_c, sec_c, gshape = new_state[i]
        if prim == "rot90":
            orient = orient.apply_rot()
        elif prim == "flip_h":
            orient = orient.apply_flip_h()
        elif prim == "flip_v":
            orient = orient.apply_flip_v()
        elif prim in _V2_TRANSLATE_PRIMITIVES:
            parity = orient.rot % 2
            cur_h = (h_inits[i] if parity == 0 else w_inits[i]) + 2 * border
            cur_w = (w_inits[i] if parity == 0 else h_inits[i]) + 2 * border
            if prim == "translate_up":
                row -= cur_h
            elif prim == "translate_down":
                row += cur_h
            elif prim == "translate_left":
                col -= cur_w
            elif prim == "translate_right":
                col += cur_w
        elif prim == "add_border":
            border += 1
            row -= 1
            col -= 1
        elif prim == "next_color":
            prim_c = _next_color_concrete(prim_c)
            if sec_c is not None:
                sec_c = _next_color_concrete(sec_c)
        elif prim == "hollow":
            if gshape == _GRID_SHAPE_HOLLOW:
                return None
            if (sec_c is not None and i < len(hollow_drops_sec)
                    and hollow_drops_sec[i]):
                sec_c = None
            gshape = _GRID_SHAPE_HOLLOW
        elif prim == "fill_interior":
            if gshape != _GRID_SHAPE_HOLLOW:
                return None
            gshape = _GRID_SHAPE_SOLID
        else:
            return None
        new_state[i] = (orient, border, row, col, prim_c, sec_c, gshape)
    return tuple(new_state)


def _enumerate_joint_transitions(
    vocab: frozenset[str], n: int,
    level_selectors: frozenset[str] = frozenset({"by_index"}),
    palette: tuple[int, ...] = (1, 2, 3, 4, 5, 6, 7, 8, 9),
) -> list[Step]:
    """Every Step template achievable under ``vocab`` × ``level_selectors``
    for a scene of ``n`` shapes.

    Selector instances are enumerated (by_index over 1..n, by_color
    over palette, others unparameterized). Relational primitives pair
    single-selector instances; non-relational use multi + single
    selectors. The step's selector is *resolved at BFS time* via
    ``_resolve_selector_on_joint_state``, which re-evaluates against
    the current state — handling dynamic selectors that change with
    state.
    """
    multi_types = [t for t in level_selectors
                   if t in {"ALL", "by_color", "is_hollow"}]
    single_types = [t for t in level_selectors
                    if t in {"by_index", "topmost", "bottommost",
                             "leftmost", "rightmost"}]

    def _sel_instances(types: list[str]) -> list[Selector]:
        out: list[Selector] = []
        for t in types:
            if t == "by_index":
                for k in range(1, n + 1):
                    out.append(Selector("by_index", param=k))
            elif t == "by_color":
                for c in palette:
                    out.append(Selector("by_color", param=int(c)))
            else:
                out.append(Selector(t))
        return out

    multi_sels = _sel_instances(multi_types)
    single_sels = _sel_instances(single_types)

    steps: list[Step] = []
    for prim in vocab:
        if prim in _RELATIONAL_PRIMS:
            for src in single_sels:
                for tgt in single_sels:
                    if src == tgt:
                        continue
                    steps.append(Step(src, prim, target=tgt))
        else:
            for sel in multi_sels + single_sels:
                steps.append(Step(sel, prim))
    return steps


def _render_equivalent_joint(
    state: tuple[tuple, ...],
    target: tuple[tuple, ...],
    stabs_colored: list[frozenset[D4]],
    stabs_silhouette: list[frozenset[D4]],
) -> bool:
    """Per-shape render-equivalence for joint state.

    ``stabs_colored[i]``: D4 elements preserving shape i's colored
    pattern (position-of-primary vs position-of-secondary both fixed).
    ``stabs_silhouette[i]``: D4 elements preserving the silhouette
    ``grid != 0`` only (always a superset of stabs_colored).

    If a state has ``primary == secondary`` (or ``secondary is None``),
    the rendered shape is monochrome — its effective stab is
    ``stabs_silhouette[i]``. Otherwise it is bichromatic with stab
    ``stabs_colored[i]``.

    State and target must either both be monochrome (matching primary
    color) or both bichromatic (matching primary *and* secondary).
    """
    for i in range(len(state)):
        g, b, r, c, p, s, gs = state[i]
        tg, tb, tr, tc, tp, ts, tgs = target[i]
        if b != tb or r != tr or c != tc:
            return False
        if gs != tgs:
            return False
        state_mono = (s is None) or (p == s)
        target_mono = (ts is None) or (tp == ts)
        if state_mono != target_mono:
            return False
        if state_mono:
            if p != tp:
                return False
            if compose_d4(inverse_d4(tg), g) not in stabs_silhouette[i]:
                return False
        else:
            if p != tp or s != ts:
                return False
            if compose_d4(inverse_d4(tg), g) not in stabs_colored[i]:
                return False
    return True


def _joint_bfs(
    target: tuple[tuple, ...],
    initial: tuple[tuple, ...],
    h_inits: tuple[int, ...],
    w_inits: tuple[int, ...],
    transitions: list[Step],
    stabs_colored: list[frozenset[D4]],
    stabs_silhouette: list[frozenset[D4]],
    max_depth: int,
    hollow_drops_sec: tuple[bool, ...] = (),
) -> int:
    """Joint BFS over per-shape state tuples."""
    if _render_equivalent_joint(
        initial, target, stabs_colored, stabs_silhouette,
    ):
        return 0
    distances = {initial: 0}
    frontier = [initial]
    while frontier:
        nxt = []
        for state in frontier:
            d = distances[state]
            if d >= max_depth:
                continue
            for step in transitions:
                new_state = _apply_joint_step(
                    state, step, h_inits, w_inits, hollow_drops_sec,
                )
                if new_state is None or new_state in distances:
                    continue
                distances[new_state] = d + 1
                if _render_equivalent_joint(
                    new_state, target, stabs_colored, stabs_silhouette,
                ):
                    return d + 1
                nxt.append(new_state)
        frontier = nxt
    return max_depth + 1


def _initial_joint_state(positioned: list[Shape]) -> tuple[tuple, ...]:
    out = []
    for s in positioned:
        r, c = s.position
        gshape = _GRID_SHAPE_HOLLOW if s.is_hollow else _GRID_SHAPE_SOLID
        sec = s.secondary_color  # None if single-color
        out.append((D4_IDENTITY, 0, r, c, s.primary_color, sec, gshape))
    return tuple(out)


def _shape_hollow_drops_secondary(shape: Shape) -> bool:
    """True iff applying the ``hollow`` primitive to ``shape`` removes
    all pixels of its secondary color (i.e. secondary was only in
    interior, contour is single-colored).

    Used by Phase C to correctly track secondary_color through a
    ``hollow`` transition: when this flag is True, state.secondary
    should flip to ``None`` after hollow (the contour has only
    primary-class pixels, so the shape is effectively monochrome).
    Without this update, two programs that end with the same
    effective rendering but differ in "phantom" secondary tracking
    would be judged distinct by Phase C's render-equivalence check.
    """
    from babytheorist.primitives import hollow as _hollow_primitive
    if shape.is_null:
        return False
    if len(shape.colors) < 2:
        return False  # already monochrome — no secondary to drop
    try:
        hollowed = _hollow_primitive(shape)
    except ValueError:
        return False
    return shape.secondary_color not in hollowed.colors


def _trace_program_joint(
    program: Program, positioned: list[Shape],
) -> tuple[tuple, ...] | None:
    """Thread the program on joint state. Returns final joint state or
    ``None`` on precondition fail."""
    h_inits = tuple(s.grid.shape[0] for s in positioned)
    w_inits = tuple(s.grid.shape[1] for s in positioned)
    hollow_drops_sec = tuple(
        _shape_hollow_drops_secondary(s) for s in positioned
    )
    state = _initial_joint_state(positioned)
    for step in program:
        new_state = _apply_joint_step(
            state, step, h_inits, w_inits, hollow_drops_sec,
        )
        if new_state is None:
            return None
        state = new_state
    return state


_PHASE_C_SUPPORTED_SELECTORS = frozenset({
    "ALL", "by_index", "by_color", "is_hollow",
    "topmost", "bottommost", "leftmost", "rightmost",
})


def _is_phase_c_scope(
    program: Program,
    positioned: list[Shape],
    vocab: frozenset[str],
    level_selectors: frozenset[str],
) -> bool:
    """Phase C joint-BFS scope: vocab ⊆ 14 primitives, level selectors
    supported, shapes at most 2-color, program uses supported selectors
    only. The BFS resolves dynamic selectors (topmost/by_color/etc)
    against per-state position/color/gshape — so mixed level (e.g.
    attribute curriculum's ALL + by_color + topmost) works."""
    if not level_selectors or not level_selectors <= _PHASE_C_SUPPORTED_SELECTORS:
        return False
    if not vocab or not vocab <= _V_ALL_SUPPORTED_PRIMITIVES:
        return False
    # At least 2 axes touched (else a single-axis branch would be
    # strictly tighter).
    axis_flags = []
    if vocab & _V1_VOCAB:
        axis_flags.append("orient")
    if vocab & (_V2_TRANSLATE_PRIMITIVES | frozenset({"add_border"})):
        axis_flags.append("translate_border")
    if vocab & _COLOR_PRIMITIVES:
        axis_flags.append("color")
    if vocab & _ALIGN_PRIMITIVES:
        axis_flags.append("align")
    if vocab & frozenset({"hollow", "fill_interior"}):
        axis_flags.append("gridshape")
    phase_c_axes = {"color", "align", "gridshape"}
    if not (set(axis_flags) & phase_c_axes):
        return False
    if len(axis_flags) < 2:
        return False
    # At most 2-color shapes.
    for shape in positioned:
        if shape.is_null:
            return False
        if len(shape.colors) > 2:
            return False
    # Program: supported selectors only.
    for step in program:
        if step.selector.type not in _PHASE_C_SUPPORTED_SELECTORS:
            return False
        if (step.target is not None
                and step.target.type not in _PHASE_C_SUPPORTED_SELECTORS):
            return False
    # Conservative: Phase C's state abstraction doesn't track "ring
    # count" beyond a binary gshape flag. add_border adds layers that
    # hollow can peel, and repeated hollow on a multi-ring shape is
    # engine-valid (changes pixels) but Phase C's current model says
    # "already hollow, reject". Defer programs using hollow or
    # fill_interior until we add ring-count tracking. This covers 4
    # L4-attribute soundness bugs we surfaced.
    gshape_changing = frozenset({"hollow", "fill_interior"})
    for step in program:
        if step.primitive in gshape_changing:
            return False
    if len(positioned) < 1:
        return False
    # Depth cap — state space can blow up under full dynamic selector
    # re-resolution.
    if len(program) > 7:
        return False
    return True


def _is_scene_admissible_phase_c(
    program: Program,
    positioned: list[Shape],
    vocab: frozenset[str],
    level_selectors: frozenset[str] = frozenset({"by_index"}),
    palette: tuple[int, ...] = (1, 2, 3, 4, 5, 6, 7, 8, 9),
) -> bool:
    """Phase C joint BFS across all axes.

    Transition templates enumerated from ``vocab × level_selectors``
    on the scene size; selectors resolved per-state at BFS expansion
    time (dynamic selectors track position/color/gshape as they
    evolve).
    """
    target = _trace_program_joint(program, positioned)
    if target is None:
        return True
    initial = _initial_joint_state(positioned)
    h_inits = tuple(s.grid.shape[0] for s in positioned)
    w_inits = tuple(s.grid.shape[1] for s in positioned)
    stabs_colored = [stabilizer_of_pixel_grid(s.grid) for s in positioned]
    stabs_silhouette = [stabilizer_of_silhouette(s.grid) for s in positioned]
    hollow_drops_sec = tuple(
        _shape_hollow_drops_secondary(s) for s in positioned
    )
    transitions = _enumerate_joint_transitions(
        vocab, len(positioned), level_selectors, palette,
    )
    min_depth = _joint_bfs(
        target, initial, h_inits, w_inits, transitions,
        stabs_colored, stabs_silhouette,
        max_depth=max(0, len(program) - 1),
        hollow_drops_sec=hollow_drops_sec,
    )
    return min_depth >= len(program)


# === V1 predicate dispatcher ==============================================


def _is_v1_program_scope(program: Program) -> bool:
    """True iff every step in the program uses a D4 primitive.

    V1's joint BFS enumerates only D4 orient transitions; its state
    tracks only orient (ignoring border/position/color/grid_shape).
    A program P whose primitives are all in _V1_VOCAB only changes
    the orient axis; non-orient axes stay at their initial values.

    **Soundness under level vocab superset of D4**: even if the level
    allows non-D4 primitives in a shorter Q, such Q cannot match
    P's rendering: every non-D4 primitive (translate, add_border,
    next_color, swap_colors, align_*, hollow, fill_interior) changes
    at least one non-orient axis. For Q's final state to match P's
    — which leaves non-orient axes at their initial values — every
    non-D4 step in Q must cancel, contributing to ``|Q|`` without
    shortening it. So the minimum-length Q that matches uses only
    D4 primitives, and V1's D4-only BFS finds its length.
    """
    return bool(program) and all(
        step.primitive in _V1_VOCAB for step in program
    )


def _program_has_relational_or_target(program: Program) -> bool:
    """V1 vocab is non-relational, but be defensive."""
    return any(step.target is not None for step in program)


def _program_selectors_supported(
    program: Program, supported: frozenset[str],
) -> bool:
    """Every step's selector type is in the ``supported`` set."""
    for step in program:
        if step.selector.type not in supported:
            return False
    return True


def enumerate_subset_vocabulary(
    level_selectors: frozenset[str],
    positioned: list[Shape],
    palette: tuple[int, ...],
) -> frozenset[frozenset[int]]:
    """Enumerate every shape-subset that some selector drawn from
    ``level_selectors`` could resolve to, given this concrete
    ``positioned`` scene.

    This is the scene-concrete analog of "vocabulary of selectors":
    whatever a Q might use at some step, that selector resolves to a
    subset of current shapes at apply time. Under D4 (position- and
    color-preserving), the subset is fixed — same for every step.

    Empty subsets are dropped (an engine-fail selector can't contribute
    to any Q that runs to completion).

    Returns a set of frozensets of shape indices.
    """
    n = len(positioned)
    subsets: set[frozenset[int]] = set()

    for sel_type in level_selectors:
        if sel_type == "ALL":
            subsets.add(frozenset(range(n)))
        elif sel_type == "by_index":
            for k in range(n):
                subsets.add(frozenset({k}))
        elif sel_type == "by_color":
            for c in palette:
                idx = frozenset(
                    i for i, s in enumerate(positioned)
                    if s.primary_color == c
                )
                if idx:
                    subsets.add(idx)
        elif sel_type == "is_hollow":
            idx = frozenset(
                i for i, s in enumerate(positioned) if s.is_hollow
            )
            if idx:
                subsets.add(idx)
        elif sel_type in {"topmost", "bottommost", "leftmost", "rightmost"}:
            resolved = select(Selector(sel_type), positioned)
            if resolved:
                subsets.add(frozenset(resolved))
        else:
            # Unknown selector type — skip (scope guard above should
            # already reject).
            pass
    return frozenset(subsets)


def _render_equivalent_d4(
    state: tuple[D4, ...],
    target: tuple[D4, ...],
    stabs: list[frozenset[D4]],
) -> bool:
    """True iff ``state`` and ``target`` render identically: for every
    shape ``i``, ``target[i]^{-1} · state[i] ∈ Stab(s_i)``."""
    for i, (g, t) in enumerate(zip(state, target)):
        diff = compose_d4(inverse_d4(t), g)
        if diff not in stabs[i]:
            return False
    return True


def scene_orient_bfs(
    target: tuple[D4, ...],
    subset_vocabulary: frozenset[frozenset[int]],
    primitive_vocab: frozenset[str],
    stabs: list[frozenset[D4]],
    max_depth: int,
) -> int:
    """BFS over per-shape D4 tuples; return the minimum depth at which
    some state renders identically to ``target`` (scene-conditioned by
    per-shape stabilizers). Returns ``max_depth + 1`` if not found.

    Transition: pick ``(prim, subset)`` with ``prim ∈ primitive_vocab``
    and ``subset ∈ subset_vocabulary``; for each ``i ∈ subset``, update
    ``state[i] := compose_d4(_PRIMITIVE_TO_D4[prim], state[i])``.

    The depth-0 initial state is ``(e, e, ..., e)`` — the identity
    configuration, which corresponds to the empty program. This lets
    the check catch "P is a scene-level identity" shortcuts uniformly.
    """
    n = len(stabs)
    initial: tuple[D4, ...] = tuple(D4_IDENTITY for _ in range(n))

    if _render_equivalent_d4(initial, target, stabs):
        return 0

    distances: dict[tuple[D4, ...], int] = {initial: 0}
    frontier: list[tuple[D4, ...]] = [initial]
    prim_d4s = [(p, _PRIMITIVE_TO_D4[p]) for p in primitive_vocab
                if p in _PRIMITIVE_TO_D4]
    while frontier:
        nxt: list[tuple[D4, ...]] = []
        for state in frontier:
            d = distances[state]
            if d >= max_depth:
                continue
            for _, prim_d4 in prim_d4s:
                for subset in subset_vocabulary:
                    new_state = list(state)
                    for i in subset:
                        new_state[i] = compose_d4(prim_d4, new_state[i])
                    ns = tuple(new_state)
                    if ns in distances:
                        continue
                    distances[ns] = d + 1
                    if _render_equivalent_d4(ns, target, stabs):
                        return d + 1
                    nxt.append(ns)
        frontier = nxt
    return max_depth + 1


def _trace_program_orient(
    program: Program, positioned: list[Shape],
) -> tuple[D4, ...] | None:
    """Run ``program`` as a sequence of (subset, D4-prim) operations on
    the scene, returning the per-shape D4 tuple. Resolves selectors on
    the initial scene (D4 is position/color/grid-shape-preserving, so
    resolution is stable across steps).

    Returns ``None`` if any step's selector resolves to the empty set
    (engine would fail — defer the scene)."""
    n = len(positioned)
    state = [D4_IDENTITY] * n
    for step in program:
        indices = select(step.selector, positioned)
        if not indices:
            return None
        prim_d4 = _PRIMITIVE_TO_D4[step.primitive]
        for i in indices:
            state[i] = compose_d4(prim_d4, state[i])
    return tuple(state)


def _is_scene_admissible_v1_subset(
    program: Program, positioned: list[Shape],
    level_selectors: frozenset[str],
    palette: tuple[int, ...] = (1, 2, 3, 4, 5, 6, 7, 8, 9),
) -> bool:
    """V1 subset-based admissibility. Scope guard: program must use
    only D4 primitives (see ``_is_v1_program_scope``). The BFS always
    enumerates D4 transitions — sound under any level vocab superset
    (non-D4 Q's can't match a D4-only P's rendering).

    The subset vocabulary is enumerated from ``level_selectors`` on
    the placed scene, covering static (ALL / by_index) and dynamic
    (topmost / by_color / is_hollow / ...) selectors uniformly.
    """
    target = _trace_program_orient(program, positioned)
    if target is None:
        return True  # P fails on this scene — engine rejects, defer.
    stabs = [stabilizer_of_pixel_grid(s.grid) for s in positioned]
    subset_vocab = enumerate_subset_vocabulary(
        level_selectors, positioned, palette,
    )
    if not subset_vocab:
        return True
    # BFS only needs to explore up to depth ``len(P) - 1`` — any
    # equivalent state reached at that depth or less is a shortcut.
    min_depth = scene_orient_bfs(
        target, subset_vocab, _V1_VOCAB, stabs,
        max_depth=max(0, len(program) - 1),
    )
    # BFS returns a depth ≤ ``max_depth`` if a shortcut was found, else
    # ``max_depth + 1``. Accept iff no shortcut exists within
    # depths < len(P).
    return min_depth >= len(program)


def is_scene_admissible(
    program: Program,
    positioned: list[Shape],
    vocab: frozenset[str],
    level_selectors: frozenset[str],
) -> bool:
    """True iff no strictly shorter ``Q`` drawn from ``(vocab,
    level_selectors)`` can render to the same output grid as ``program``
    on this scene.

    Dispatches to an axis-specific branch:
      - **V1 D4 orient axis** (vocab ⊆ {rot90, flip_h, flip_v}):
        per-shape-D4-tuple BFS whose subset vocabulary is enumerated
        from ``level_selectors`` on the placed scene. Handles static
        selectors (ALL / by_index) and dynamic ones (topmost /
        by_color / is_hollow / ...) uniformly — D4 is position / color /
        grid-shape preserving, so every dynamic selector's scene-
        resolution is stable across program steps.
      - **V3 color axis** (vocab ⊆ {next_color, swap_colors},
        level_selectors ⊆ {"ALL", "by_index"}, single-color shapes):
        scene-parameterized Tier 4 joint BFS.
      - **V3 position axis** (vocab ⊆ {align_row, align_col},
        level_selectors = {by_index}): scene-parameterized Tier 5.

    Any other combination (mixed axes, unsupported selectors, position-
    changing primitives without a matching branch) **defers** (returns
    ``True``). The existing ``_generate_pair`` backstops (identity /
    grid-sequence-distinct / optional brute-force) still apply
    downstream.

    Empty program: trivially admissible.
    """
    if not program:
        return True

    # V1 D4 orient axis — fires whenever the program uses only D4
    # primitives. Level vocab may have more; non-D4 Q's can't match
    # a D4-only P's rendering (they change non-orient axes). Level
    # selectors must be stable under D4 (all default selectors are).
    if _is_v1_program_scope(program):
        if _program_has_relational_or_target(program):
            return True
        if not _program_selectors_supported(program, _V1_SUPPORTED_SELECTORS):
            return True
        if not level_selectors <= _V1_SUPPORTED_SELECTORS:
            return True
        return _is_scene_admissible_v1_subset(
            program, positioned, level_selectors,
        )

    # V2 orient + translate + add_border — by_index per-shape BFS.
    if _is_v2_scope(program, positioned, vocab, level_selectors):
        return _is_scene_admissible_v2(program, positioned, vocab)

    # V3 color axis — scene-parameterized Tier 4 BFS.
    if _is_v3_color_scope(program, positioned, vocab, level_selectors):
        return _is_scene_admissible_v3_color(
            program, positioned, vocab, level_selectors,
        )

    # V3 position axis — scene-parameterized Tier 5 BFS.
    if _is_v3_position_scope(program, positioned, vocab, level_selectors):
        return _is_scene_admissible_v3_position(program, positioned, vocab)

    # Phase C — mixed-axis joint BFS (catch-all for multi-axis vocabs).
    if _is_phase_c_scope(program, positioned, vocab, level_selectors):
        return _is_scene_admissible_phase_c(
            program, positioned, vocab, level_selectors,
        )

    # Out of scope — defer.
    return True


def scene_verdict(
    program: Program,
    positioned: list[Shape],
    vocab: frozenset[str],
    level_selectors: frozenset[str],
) -> tuple[bool, bool]:
    """Companion to ``is_scene_admissible`` that also reports whether
    any branch actually analyzed the case (vs deferring).

    Returns ``(admissible, analyzed)``:
      - ``admissible``: same verdict as ``is_scene_admissible``. True
        when no shortcut is detected OR when all branches defer; False
        when a branch positively rejects.
      - ``analyzed``: True iff some branch accepted or rejected on an
        actual analysis; False iff every branch deferred (i.e. the
        scene is outside all supported scopes and the admissible=True
        result is a fallback, not a verified accept).

    Callers that want airtight correctness should either (a) treat
    ``analyzed=False`` as "symbolic uncertainty — fall back to
    brute-force" or (b) reject such scenes.
    """
    if not program:
        return True, True  # empty program — trivially analyzed

    if _is_v1_program_scope(program):
        if _program_has_relational_or_target(program):
            return True, False
        if not _program_selectors_supported(program, _V1_SUPPORTED_SELECTORS):
            return True, False
        if not level_selectors <= _V1_SUPPORTED_SELECTORS:
            return True, False
        return (
            _is_scene_admissible_v1_subset(
                program, positioned, level_selectors,
            ),
            True,
        )

    if _is_v2_scope(program, positioned, vocab, level_selectors):
        return (
            _is_scene_admissible_v2(program, positioned, vocab),
            True,
        )

    if _is_v3_color_scope(program, positioned, vocab, level_selectors):
        return (
            _is_scene_admissible_v3_color(
                program, positioned, vocab, level_selectors,
            ),
            True,
        )

    if _is_v3_position_scope(program, positioned, vocab, level_selectors):
        return (
            _is_scene_admissible_v3_position(program, positioned, vocab),
            True,
        )

    if _is_phase_c_scope(program, positioned, vocab, level_selectors):
        return (
            _is_scene_admissible_phase_c(
                program, positioned, vocab, level_selectors,
            ),
            True,
        )

    return True, False  # deferred by every branch
